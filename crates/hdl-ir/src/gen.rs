//! Template-based generation from the IR — backs `hdlsim gen tb <top>`.
//!
//! Templates use only constructs hdlsim itself compiles, so a generated
//! testbench round-trips through `hdlsim check` (covered by integration
//! tests in the `hdlsim` crate).

use crate::ir::{Design, Dir, ModuleIr, PortIr};
use crate::value::{is_xz, Value};
use hdl_syntax::language::Language;

/// Generate a testbench skeleton for `top` in `lang`, as source text.
pub fn testbench(design: &Design, top: &str, lang: Language) -> Result<String, String> {
    let m = design
        .modules
        .iter()
        .find(|m| m.name == top)
        .ok_or_else(|| format!("no module named '{}'", top))?;
    Ok(match lang {
        Language::Verilog => verilog_tb(m),
        Language::Vhdl => vhdl_tb(m),
    })
}

fn width_of(m: &ModuleIr, p: &PortIr) -> usize {
    m.signals
        .get(p.sig as usize)
        .map(|s| s.width.max(1))
        .unwrap_or(1)
}

/// Decimal value of a constant, if every bit is known and it fits in u64.
fn value_u64(v: &Value) -> Option<u64> {
    if v.bits.len() > 64 || v.bits.iter().any(|b| is_xz(*b) || *b > 1) {
        return None;
    }
    Some(
        v.bits
            .iter()
            .enumerate()
            .fold(0u64, |acc, (i, b)| acc | ((*b as u64) << i)),
    )
}

fn is_reset_like(name: &str) -> bool {
    let n = name.to_ascii_lowercase();
    n.contains("rst") || n.contains("reset")
}

fn has_clk(m: &ModuleIr) -> bool {
    m.ports.iter().any(|p| p.name == "clk")
}

fn verilog_tb(m: &ModuleIr) -> String {
    let tb = format!("tb_{}", m.name);
    let mut s = String::new();
    s.push_str("`timescale 1ns/1ps\n");
    s.push_str(&format!(
        "// Testbench for {} -- generated by hdlsim gen tb. Fill in the stimulus below.\n",
        m.name
    ));
    s.push_str(&format!("module {};\n", tb));
    for p in &m.ports {
        let w = width_of(m, p);
        let range = if w > 1 {
            format!("[{}:0] ", w - 1)
        } else {
            String::new()
        };
        let kw = match p.dir {
            Dir::In => "reg",
            Dir::Out | Dir::Inout => "wire",
        };
        let init = match p.dir {
            Dir::In if p.name == "clk" => " = 0",
            Dir::In if is_reset_like(&p.name) => " = 1",
            _ => "",
        };
        s.push_str(&format!("    {} {}{}{};\n", kw, range, p.name, init));
    }
    s.push('\n');
    if m.params.is_empty() {
        s.push_str(&format!("    {} dut (\n", m.name));
    } else {
        s.push_str(&format!("    {} #(\n", m.name));
        for (i, p) in m.params.iter().enumerate() {
            let v = value_u64(&p.default)
                .map(|v| v.to_string())
                .unwrap_or_else(|| "0".to_string());
            let comma = if i + 1 == m.params.len() { "" } else { "," };
            s.push_str(&format!("        .{}({}){}\n", p.name, v, comma));
        }
        s.push_str("    ) dut (\n");
    }
    for (i, p) in m.ports.iter().enumerate() {
        let comma = if i + 1 == m.ports.len() { "" } else { "," };
        s.push_str(&format!("        .{}({}){}\n", p.name, p.name, comma));
    }
    s.push_str("    );\n\n");
    if has_clk(m) {
        s.push_str("    always #5 clk = ~clk;\n\n");
    }
    s.push_str("    initial begin\n");
    let resets: Vec<&PortIr> = m
        .ports
        .iter()
        .filter(|p| p.dir == Dir::In && is_reset_like(&p.name))
        .collect();
    for p in &resets {
        s.push_str(&format!("        {} = 1;\n", p.name));
    }
    if !resets.is_empty() {
        s.push_str("        #10;\n");
        for p in &resets {
            s.push_str(&format!("        {} = 0;\n", p.name));
        }
    }
    s.push_str("        // TODO: drive stimulus here\n        #100;\n");
    s.push_str(&format!("        $display(\"{} done\");\n", tb));
    s.push_str("        $finish;\n    end\nendmodule\n");
    s
}

fn vhdl_tb(m: &ModuleIr) -> String {
    let tb = format!("tb_{}", m.name);
    let w = m.ports.iter().map(|p| p.name.len()).max().unwrap_or(0);
    let mut s = String::new();
    s.push_str(&format!(
        "-- Testbench for {} -- generated by hdlsim gen tb. Fill in the stimulus below.\n",
        m.name
    ));
    s.push_str("library ieee;\nuse ieee.std_logic_1164.all;\n\n");
    s.push_str(&format!("entity {} is\n", tb));
    if !m.params.is_empty() {
        s.push_str("    generic (\n");
        for (i, p) in m.params.iter().enumerate() {
            let v = value_u64(&p.default)
                .map(|v| v.to_string())
                .unwrap_or_else(|| "0".to_string());
            let semi = if i + 1 == m.params.len() { "" } else { ";" };
            s.push_str(&format!("        {} : integer := {}{}\n", p.name, v, semi));
        }
        s.push_str("    );\n");
    }
    s.push_str("end entity;\n\n");
    s.push_str(&format!("architecture sim of {} is\n", tb));
    for p in &m.ports {
        let width = width_of(m, p);
        let (ty, init) = if width == 1 {
            let init = if is_reset_like(&p.name) {
                " := '1'"
            } else {
                " := '0'"
            };
            ("std_logic", init)
        } else {
            (&format!("std_logic_vector({} downto 0)", width - 1)[..], "")
        };
        s.push_str(&format!(
            "    signal {:w$} : {}{};\n",
            p.name,
            ty,
            init,
            w = w
        ));
    }
    s.push_str("begin\n");
    s.push_str(&format!("    dut : entity work.{}\n", m.name));
    if !m.params.is_empty() {
        s.push_str("        generic map (\n");
        for (i, p) in m.params.iter().enumerate() {
            let v = value_u64(&p.default)
                .map(|v| v.to_string())
                .unwrap_or_else(|| "0".to_string());
            let comma = if i + 1 == m.params.len() { "" } else { "," };
            s.push_str(&format!("            {} => {}{}\n", p.name, v, comma));
        }
        s.push_str("        )\n");
    }
    if !m.ports.is_empty() {
        s.push_str("        port map (\n");
        for (i, p) in m.ports.iter().enumerate() {
            let comma = if i + 1 == m.ports.len() { "" } else { "," };
            s.push_str(&format!("            {} => {}{}\n", p.name, p.name, comma));
        }
        s.push_str("        );\n\n");
    } else {
        s.push('\n');
    }
    if has_clk(m) {
        s.push_str("    process\n    begin\n        clk <= not clk;\n        wait for 5 ns;\n    end process;\n\n");
    }
    s.push_str("    stim : process\n    begin\n");
    let resets: Vec<&PortIr> = m
        .ports
        .iter()
        .filter(|p| p.dir == Dir::In && is_reset_like(&p.name))
        .collect();
    for p in &resets {
        s.push_str(&format!("        {} <= '1';\n", p.name));
    }
    if !resets.is_empty() {
        s.push_str("        wait for 10 ns;\n");
        for p in &resets {
            s.push_str(&format!("        {} <= '0';\n", p.name));
        }
    }
    s.push_str("        -- TODO: drive stimulus here\n        wait for 100 ns;\n");
    s.push_str(&format!("        report \"{} done\";\n", tb));
    s.push_str("        std.env.finish;\n        wait;\n    end process;\n");
    s.push_str("end architecture;\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::{ParamIr, SigKind, SignalIr};

    fn sig(name: &str, width: usize, kind: SigKind) -> SignalIr {
        SignalIr {
            name: name.to_string(),
            width,
            kind,
            init: None,
            mem: None,
            signed: false,
        }
    }

    fn counter() -> ModuleIr {
        ModuleIr {
            name: "counter".to_string(),
            params: vec![],
            ports: vec![
                PortIr {
                    name: "clk".to_string(),
                    dir: Dir::In,
                    sig: 0,
                },
                PortIr {
                    name: "rst".to_string(),
                    dir: Dir::In,
                    sig: 1,
                },
                PortIr {
                    name: "q".to_string(),
                    dir: Dir::Out,
                    sig: 2,
                },
            ],
            signals: vec![
                sig("clk", 1, SigKind::Input),
                sig("rst", 1, SigKind::Input),
                sig("q", 8, SigKind::Output),
            ],
            assigns: vec![],
            processes: vec![],
            functions: vec![],
            instances: vec![],
            time_unit_fs: 1_000_000,
        }
    }

    fn design_with(m: ModuleIr) -> Design {
        Design {
            modules: vec![m],
            top: None,
            packages: Default::default(),
        }
    }

    #[test]
    fn verilog_tb_has_dut_ports_clock_and_stimulus() {
        let src = testbench(&design_with(counter()), "counter", Language::Verilog).unwrap();
        assert!(src.contains("module tb_counter;"), "{}", src);
        assert!(src.contains("reg clk = 0;"), "{}", src);
        assert!(src.contains("reg rst = 1;"), "{}", src);
        assert!(src.contains("wire [7:0] q;"), "{}", src);
        assert!(src.contains("counter dut ("), "{}", src);
        assert!(src.contains(".clk(clk),"), "{}", src);
        assert!(src.contains(".q(q)"), "{}", src);
        assert!(src.contains("always #5 clk = ~clk;"), "{}", src);
        assert!(src.contains("rst = 0;"), "{}", src);
        assert!(src.contains("$finish;"), "{}", src);
    }

    #[test]
    fn vhdl_tb_has_entity_port_map_and_finish() {
        let src = testbench(&design_with(counter()), "counter", Language::Vhdl).unwrap();
        assert!(src.contains("entity tb_counter is"), "{}", src);
        assert!(src.contains("signal clk : std_logic := '0';"), "{}", src);
        assert!(
            src.contains("signal q   : std_logic_vector(7 downto 0);"),
            "{}",
            src
        );
        assert!(src.contains("dut : entity work.counter"), "{}", src);
        assert!(src.contains("clk => clk,"), "{}", src);
        assert!(src.contains("clk <= not clk;"), "{}", src);
        assert!(src.contains("rst <= '0';"), "{}", src);
        assert!(src.contains("std.env.finish;"), "{}", src);
    }

    #[test]
    fn params_become_parameter_and_generic_maps() {
        let mut m = counter();
        m.params = vec![ParamIr {
            name: "W".to_string(),
            default: Value::from_u64(32, 8),
        }];
        let v = testbench(&design_with(m.clone()), "counter", Language::Verilog).unwrap();
        assert!(v.contains("counter #("), "{}", v);
        assert!(v.contains(".W(8)"), "{}", v);
        let h = testbench(&design_with(m), "counter", Language::Vhdl).unwrap();
        assert!(h.contains("W : integer := 8"), "{}", h);
        assert!(h.contains("W => 8"), "{}", h);
    }

    #[test]
    fn unknown_top_is_an_error() {
        assert!(testbench(&design_with(counter()), "nope", Language::Verilog).is_err());
    }
}
