//! Project-file generation for external tools — part of hdlsim's external
//! interface.
//!
//! Other tools can either shell out to `hdlsim project …` or depend on this
//! crate and call [`generate`] directly with a [`ProjectSpec`]. Formats are a
//! closed enum + one function each (`vivado_tcl`, `manifest_json`); adding a
//! new tool (e.g. Quartus, Riviera-PRO, a Makefile) is one new variant and
//! one new function, no changes elsewhere.
//!
//! The JSON manifest is the machine-readable interface: it lists every source
//! file with its language, logical library and contained design units, plus
//! the library map — enough for any tool to reconstruct the compile order.

use hdl_lib::LibraryManager;
use hdl_syntax::language::Language;
use std::path::{Path, PathBuf};

/// Everything needed to describe a design as a foreign-tool project.
#[derive(Clone, Debug, Default)]
pub struct ProjectSpec {
    /// Project name (used for the Vivado project directory / JSON `name`).
    pub name: String,
    /// Explicit source files.
    pub files: Vec<PathBuf>,
    /// Logical libraries: `(name, directory)` — from `hdlsim.ini` / `-L`.
    pub libraries: Vec<(String, PathBuf)>,
    /// Verilog include directories.
    pub include_dirs: Vec<PathBuf>,
    /// Synthesis/elaboration top entity or module.
    pub top: Option<String>,
    /// Simulation (testbench) top.
    pub sim_top: Option<String>,
    /// FPGA part for Vivado (`--part`).
    pub part: Option<String>,
}

/// Supported project formats. New tools = one new variant + one generator.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ProjectFormat {
    /// Xilinx Vivado batch TCL script.
    Vivado,
    /// Tool-neutral JSON manifest (for any external tool).
    Json,
}

impl ProjectFormat {
    pub fn parse(s: &str) -> Result<ProjectFormat, String> {
        match s {
            "vivado" => Ok(ProjectFormat::Vivado),
            "json" | "manifest" => Ok(ProjectFormat::Json),
            other => Err(format!(
                "unknown project format '{}' (available: vivado, json)",
                other
            )),
        }
    }
    pub fn extension(&self) -> &'static str {
        match self {
            ProjectFormat::Vivado => "tcl",
            ProjectFormat::Json => "json",
        }
    }
}

/// Generate the project file text for `spec` in `format`. `mgr` supplies the
/// library contents for the JSON manifest (may be `None` → libraries are
/// listed from `spec.libraries` without unit scanning).
pub fn generate(
    spec: &ProjectSpec,
    format: ProjectFormat,
    mgr: Option<&LibraryManager>,
) -> Result<String, String> {
    match format {
        ProjectFormat::Vivado => Ok(vivado_tcl(spec)),
        ProjectFormat::Json => manifest_json(spec, mgr),
    }
}

/// Which logical library a file belongs to (longest matching library dir),
/// defaulting to `work`.
fn library_of(spec: &ProjectSpec, file: &Path) -> String {
    let canon = std::fs::canonicalize(file).unwrap_or_else(|_| file.to_path_buf());
    let mut best: Option<(usize, &str)> = None;
    for (name, dir) in &spec.libraries {
        if let Ok(cdir) = std::fs::canonicalize(dir) {
            if canon.starts_with(&cdir) {
                let l = cdir.as_os_str().len();
                if best.is_none_or(|(bl, _)| l > bl) {
                    best = Some((l, name));
                }
            }
        }
    }
    best.map(|(_, n)| n.to_string())
        .unwrap_or_else(|| "work".to_string())
}

fn tcl_str(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('[', "\\[")
        .replace(']', "\\]")
}

fn tcl_path(p: &Path) -> String {
    let abs = std::fs::canonicalize(p).unwrap_or_else(|_| p.to_path_buf());
    tcl_str(&abs.display().to_string()).replace(' ', "\\ ")
}

/// Xilinx Vivado batch script: create project, add files grouped by logical
/// library, set tops, optionally launch simulation.
pub fn vivado_tcl(spec: &ProjectSpec) -> String {
    let name = if spec.name.is_empty() {
        "hdlsim_proj"
    } else {
        &spec.name
    };
    let part = spec.part.as_deref().unwrap_or("xc7k325tffg900-2");
    let has_vhdl = spec
        .files
        .iter()
        .any(|f| matches!(Language::from_path(f), Some(Language::Vhdl)));
    let has_verilog = spec
        .files
        .iter()
        .any(|f| matches!(Language::from_path(f), Some(Language::Verilog)));
    let lang = if has_vhdl && !has_verilog {
        "VHDL"
    } else if has_verilog && !has_vhdl {
        "Verilog"
    } else {
        "Mixed"
    };
    let mut t = String::new();
    t.push_str("# Generated by hdlsim — Xilinx Vivado project script\n");
    t.push_str("# usage: vivado -mode batch -source <this file>\n\n");
    t.push_str(&format!(
        "create_project -force {} ./{}_proj -part {}\n",
        name, name, part
    ));
    t.push_str(&format!(
        "set_property target_language {} [current_project]\n\n",
        lang
    ));
    if !spec.files.is_empty() {
        t.push_str("add_files -norecurse [list \\\n");
        for f in &spec.files {
            t.push_str(&format!("  {} \\\n", tcl_path(f)));
        }
        t.truncate(t.len() - 2); // drop trailing " \"
        t.push_str("\n]\n");
        // Assign each file to its logical library.
        for f in &spec.files {
            let lib = library_of(spec, f);
            t.push_str(&format!(
                "set_property library {} [get_files {{{}}}]\n",
                lib,
                tcl_path(f)
            ));
        }
        t.push('\n');
    }
    if let Some(top) = &spec.top {
        t.push_str(&format!(
            "set_property top {} [get_filesets sources_1]\n",
            top
        ));
    }
    if let Some(sim) = &spec.sim_top {
        t.push_str(&format!("set_property top {} [get_filesets sim_1]\n", sim));
        t.push_str("launch_simulation\n");
    }
    t
}

/// Tool-neutral JSON manifest describing files, libraries and design units.
pub fn manifest_json(spec: &ProjectSpec, mgr: Option<&LibraryManager>) -> Result<String, String> {
    let mut j = String::new();
    j.push_str("{\n");
    j.push_str(&format!(
        "  \"tool\": \"hdlsim\",\n  \"version\": \"{}\",\n",
        env!("CARGO_PKG_VERSION")
    ));
    j.push_str(&format!("  \"name\": {},\n", js(&spec.name)));
    j.push_str(&format!(
        "  \"top\": {},\n  \"sim_top\": {},\n",
        opt_js(spec.top.as_deref()),
        opt_js(spec.sim_top.as_deref())
    ));
    // files
    j.push_str("  \"files\": [\n");
    for (i, f) in spec.files.iter().enumerate() {
        let lang = Language::from_path(f)
            .map(|l| format!("{:?}", l).to_lowercase())
            .unwrap_or_else(|| "unknown".into());
        let units = hdl_lib::providers::units_in_file(f);
        j.push_str("    {\"path\": ");
        j.push_str(&js(&f.display().to_string()));
        j.push_str(", \"language\": ");
        j.push_str(&js(&lang));
        j.push_str(", \"library\": ");
        j.push_str(&js(&library_of(spec, f)));
        j.push_str(", \"units\": [");
        j.push_str(&units.iter().map(|u| js(u)).collect::<Vec<_>>().join(", "));
        j.push_str("]}");
        j.push_str(if i + 1 < spec.files.len() {
            ",\n"
        } else {
            "\n"
        });
    }
    j.push_str("  ],\n");
    // libraries with scanned units
    j.push_str("  \"libraries\": [\n");
    let libs: Vec<(String, Vec<(String, PathBuf)>)> = match mgr {
        Some(m) => m.scan_libraries(),
        None => spec
            .libraries
            .iter()
            .map(|(n, p)| {
                let mut units = Vec::new();
                for f in walk_files(p) {
                    for u in hdl_lib::providers::units_in_file(&f) {
                        units.push((u, f.clone()));
                    }
                }
                (n.clone(), units)
            })
            .collect(),
    };
    for (i, (name, units)) in libs.iter().enumerate() {
        j.push_str("    {\"name\": ");
        j.push_str(&js(name));
        j.push_str(", \"units\": [");
        j.push_str(
            &units
                .iter()
                .map(|(u, f)| {
                    let mut e = String::from("{\"name\": ");
                    e.push_str(&js(u));
                    e.push_str(", \"file\": ");
                    e.push_str(&js(&f.display().to_string()));
                    e.push('}');
                    e
                })
                .collect::<Vec<_>>()
                .join(", "),
        );
        j.push_str("]}");
        j.push_str(if i + 1 < libs.len() { ",\n" } else { "\n" });
    }
    j.push_str("  ],\n");
    j.push_str("  \"include_dirs\": [");
    j.push_str(
        &spec
            .include_dirs
            .iter()
            .map(|d| js(&d.display().to_string()))
            .collect::<Vec<_>>()
            .join(", "),
    );
    j.push_str("]\n}\n");
    Ok(j)
}

fn walk_files(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(d) = stack.pop() {
        if let Ok(rd) = std::fs::read_dir(&d) {
            for e in rd.flatten() {
                let p = e.path();
                if p.is_dir() {
                    stack.push(p);
                } else if matches!(
                    p.extension().and_then(|e| e.to_str()),
                    Some("vhd" | "vhdl" | "v" | "sv")
                ) {
                    out.push(p);
                }
            }
        }
    }
    out
}

fn js(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn opt_js(s: Option<&str>) -> String {
    match s {
        Some(s) => js(s),
        None => "null".to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec() -> ProjectSpec {
        ProjectSpec {
            name: "demo".into(),
            files: vec![PathBuf::from("examples/vhdl-counter/counter.vhd")],
            libraries: vec![("work".into(), PathBuf::from("."))],
            include_dirs: vec![],
            top: Some("counter".into()),
            sim_top: Some("tb_counter".into()),
            part: None,
        }
    }

    #[test]
    fn vivado_tcl_has_project_files_and_tops() {
        let t = vivado_tcl(&spec());
        assert!(
            t.contains("create_project -force demo ./demo_proj -part xc7k325tffg900-2"),
            "{}",
            t
        );
        assert!(t.contains("add_files -norecurse"), "{}", t);
        assert!(t.contains("counter.vhd"), "{}", t);
        assert!(t.contains("set_property library work"), "{}", t);
        assert!(
            t.contains("set_property top counter [get_filesets sources_1]"),
            "{}",
            t
        );
        assert!(
            t.contains("set_property top tb_counter [get_filesets sim_1]"),
            "{}",
            t
        );
        assert!(t.contains("launch_simulation"), "{}", t);
        assert!(t.contains("target_language VHDL"), "{}", t);
    }

    #[test]
    fn json_manifest_lists_units() {
        // Use a real example file so units_in_file can parse it.
        let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../examples/vhdl-counter");
        let mut s = spec();
        s.files = vec![dir.join("counter.vhd"), dir.join("tb_counter.vhd")];
        s.libraries = vec![("work".into(), dir.clone())];
        let j = manifest_json(&s, None).unwrap();
        assert!(j.contains("\"tool\": \"hdlsim\""), "{}", j);
        assert!(
            j.contains("\"units\": [\"counter\"]"),
            "units missing: {}",
            j
        );
        assert!(j.contains("\"units\": [\"tb_counter\"]"), "{}", j);
        assert!(j.contains("\"language\": \"vhdl\""), "{}", j);
        assert!(j.contains("\"sim_top\": \"tb_counter\""), "{}", j);
        // Library scan must find both entities in the work library.
        assert!(j.contains("\"name\": \"work\""), "{}", j);
        assert!(j.contains("\"file\": "), "{}", j);
        assert!(j.trim_end().ends_with('}'), "{}", j);
    }

    #[test]
    fn format_parsing() {
        assert_eq!(
            ProjectFormat::parse("vivado").unwrap(),
            ProjectFormat::Vivado
        );
        assert_eq!(ProjectFormat::parse("json").unwrap(), ProjectFormat::Json);
        assert!(ProjectFormat::parse("quartus").is_err());
        assert_eq!(ProjectFormat::Vivado.extension(), "tcl");
    }
}
